// TypeScript from the protocol schema, generated in CI and development only (docs/WEB.md P2).
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = resolve(root, "../core/src/endbotd/web_protocol.schema.json");
const output = resolve(root, "src/generated");
const schema = JSON.parse(readFileSync(schemaPath, "utf8"));

mkdirSync(output, { recursive: true });
const banner = "// Generated by scripts/generate-protocol.mjs. Do not edit.\n";
writeFileSync(resolve(output, "protocol-version.ts"), `${banner}export const WEB_PROTOCOL = ${schema.version};\n`);
writeFileSync(resolve(output, "protocol.ts"), await compile(schema, "EndbotWebProtocol", { bannerComment: banner }));
