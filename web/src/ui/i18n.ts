export const language: "en" | "ja" = navigator.language.toLowerCase().startsWith("ja") ? "ja" : "en";
const messages: Messages = language === "ja" ? japanese : english;

export function t(key: keyof Messages, params: Record<string, string | number> = {}): string {
  return messages[key].replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? ""));
}

export function errorText(code: string): string {
  const key = `error_${code}` as keyof Messages;
  return key in messages ? messages[key] : messages.error_generic;
}

export function formatDate(seconds: number): string {
  return new Date(seconds * 1000).toLocaleString(language);
}
